SELECT
  employee_name,
  COUNT(*) as months_count,
  ROUND(AVG(salary_amount), 2) as avg_salary,
  MIN(salary_amount) as min_salary,
  MAX(salary_amount) as max_salary
FROM salaries
GROUP BY employee_name
ORDER BY employee_name;